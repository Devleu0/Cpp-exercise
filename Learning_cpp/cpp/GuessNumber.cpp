#include <iostream> 
#include <cstdlib>  
#include <ctime>    

/*
🎮 숫자 맞추기 게임 (Guess the Number)
이 게임은 컴퓨터가 1부터 100 사이의 숫자 하나를 무작위로 정하면, 플레이어가 그 숫자를 맞추는 간단한 방식입니다. 
플레이어가 숫자를 입력할 때마다 컴퓨터는 정답보다 높은지, 낮은지를 알려주어 힌트를 줍니다.

📝 게임 설계
게임 시작: 게임이 시작되면 환영 메시지를 보여주고, 1부터 100 사이의 무작위 숫자를 생성합니다.

사용자 입력: 플레이어에게 숫자를 입력하라는 메시지를 표시합니다.

추리 및 피드백

플레이어가 입력한 숫자가 정답보다 크면 "너무 큽니다!"라고 알려줍니다.

플레이어가 입력한 숫자가 정답보다 작으면 "너무 작습니다!"라고 알려줍니다.

플레이어가 입력한 숫자가 정답과 같으면 "정답입니다!" 메시지와 함께 몇 번 만에 맞췄는지 시도 횟수를 보여줍니다.

게임 루프: 플레이어가 정답을 맞출 때까지 2번과 3번 과정을 반복합니다.

게임 종료: 정답을 맞추면 게임이 종료됩니다.
*/

int main() {
    // 난수 생성기 초기화 (매번 다른 숫자가 나오도록 설정)
    srand(static_cast<unsigned int>(time(0)));

    // 1부터 100 사이의 무작위 숫자 생성
    int secretNumber = rand() % 100 + 1;
    int guess = 0;
    int tries = 0;

    // 게임 시작 메시지 출력
    std::cout << "=================================\n";
    std::cout << "      숫자 맞추기 게임 🎯\n";
    std::cout << "=================================\n";
    std::cout << "1부터 100 사이의 숫자를 맞춰보세요!\n\n";

    // do-while 루프: 플레이어가 정답을 맞출 때까지 계속 반복
    do {
        std::cout << "숫자를 입력하세요: ";
        std::cin >> guess;
        tries++; // 시도 횟수 증가

        if (guess > secretNumber) {
            std::cout << ">> 너무 큽니다! 🤔\n\n";
        }
        else if (guess < secretNumber) {
            std::cout << ">> 너무 작습니다! 👀\n\n";
        }
        else {
            std::cout << "\n=================================\n";
            std::cout << "🎉 정답입니다! 축하합니다! 🎉\n";
            std::cout << "정답은 " << secretNumber << "이었습니다.\n";
            std::cout << "시도 횟수: " << tries << "번\n";
            std::cout << "=================================\n";
        }
    } while (guess != secretNumber);

    return 0;
}